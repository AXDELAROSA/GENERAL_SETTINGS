		UPDATE	SUB_SISTEMA_TAG
			SET	D_SUB_SISTEMA_TAG			= @PP_D_SUB_SISTEMA_TAG
		WHERE	K_SUB_SISTEMA_TAG=@PP_K_SUB_SISTEMA_TAG

	-- =========================================================
GO

