	SELECT	@VP_K_EXISTE =	K_SISTEMA_CONTROL_PERMISO
							FROM	SISTEMA_CONTROL_PERMISO
							WHERE	K_SISTEMA_CONTROL_PERMISO=@PP_K_SISTEMA_CONTROL_PERMISO
