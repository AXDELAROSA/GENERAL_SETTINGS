IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[PG_RN_RUTA_ARCHIVO]') AND type in (N'P', N'PC'))
	DROP PROCEDURE [dbo].[PG_RN_RUTA_ARCHIVO]
GO
/*
	EXEC [PG_RN_RUTA_ARCHIVO] 0,0, 'INSPECCION_IMG_MASTER_QC', 'FWLNPX7'
*/
CREATE PROCEDURE [dbo].[PG_RN_RUTA_ARCHIVO]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO_ACCION		INT,
	-- ===========================		
	@PP_D_RUTA_ARCHIVO			VARCHAR(255),
	@PP_NOMBRE_ARCHIVO			VARCHAR(255)
	-- ===========================		
AS

	DECLARE @VP_RUTA_ARCHIVO		VARCHAR(255) = '' 
	
	-- /////////////////////////////////////////////////////
		SELECT	@VP_RUTA_ARCHIVO = CONCAT(SERVIDOR, RUTA,NOMBRE_ARCHIVO, D_TIPO_RUTA_ARCHIVO) 
		FROM	BD_GENERAL.DBO.RUTA_ARCHIVO 
		INNER JOIN TIPO_RUTA_ARCHIVO ON TIPO_RUTA_ARCHIVO.K_TIPO_RUTA_ARCHIVO = RUTA_ARCHIVO.K_TIPO_RUTA_ARCHIVO
		WHERE	D_RUTA_ARCHIVO = @PP_D_RUTA_ARCHIVO	
		AND		NOMBRE_ARCHIVO = @PP_NOMBRE_ARCHIVO
		AND		K_ESTATUS_RUTA_ARCHIVO = 1 -- ACTIVO
				
		IF @VP_RUTA_ARCHIVO IS NULL
			SET @VP_RUTA_ARCHIVO = ''
	-- /////////////////////////////////////////////////////
	
	SELECT @VP_RUTA_ARCHIVO AS RUTA_ARCHIVO

	-- /////////////////////////////////////////////////////
GO


