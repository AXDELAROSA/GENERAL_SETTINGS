CREATE PROCEDURE [dbo].[PG_SK_USER_PEARL_AUTORIZAR]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO_ACCION		INT,
	-- ===========================
	@PP_USER					VARCHAR(50),
	@PP_PASSWORD				VARCHAR(50),
	@PP_LOCACION				VARCHAR(50) = ''
AS
	DECLARE	 @VP_MENSAJE		NVARCHAR(MAX)	= ''
			,@VP_K_CODIGO		INT
			,@VP_NOMBRE			VARCHAR(500)
			,@VP_APELLIDO		VARCHAR(500)
BEGIN TRANSACTION 
BEGIN TRY
	-- ///////////////////////////////////////////
	DECLARE @VP_TIPO_GRUPO_APROBADOR INT	= 150			---	= 21	--- ES LA LOCACIÓN DEFAULT PARA USUARIOS DE CALIDAD
	
	IF @PP_LOCACION	= 'MRD'---@PP_TIPO_TRANSACCION <> 'Cuarentena'
	BEGIN
		SET	@VP_TIPO_GRUPO_APROBADOR	= 30	--	AUTORIZAR SALIDA MRD
	END

	SELECT	@VP_K_CODIGO		= K_USUARIO,
			
			@VP_NOMBRE			=	(CASE	
										WHEN NOMBRE	= ''											THEN	D_USUARIO_PEARL
										WHEN CHARINDEX(' ',NOMBRE) = 0								THEN UPPER(LEFT(NOMBRE,1)) + LOWER(SUBSTRING(NOMBRE,2,LEN(NOMBRE)))
										WHEN CHARINDEX(' ',NOMBRE) <> 0 AND  K_USUARIO_PEARL <> 47	THEN UPPER(LEFT(SUBSTRING( NOMBRE, 1, CHARINDEX(' ', NOMBRE)-1),1)) + LOWER(SUBSTRING(SUBSTRING( NOMBRE, 1, CHARINDEX(' ', NOMBRE)-1),2,LEN(SUBSTRING( NOMBRE, 1, CHARINDEX(' ', NOMBRE)-1)))) 
										WHEN CHARINDEX(' ',NOMBRE) <> 0 AND  K_USUARIO_PEARL = 47	THEN 'Miguel'---UPPER(LEFT(SUBSTRING( NOMBRE, CHARINDEX(' ', NOMBRE) + 1, 20),1))+LOWER(SUBSTRING(SUBSTRING( NOMBRE, CHARINDEX(' ', NOMBRE) + 1, 20),2,LEN(SUBSTRING( NOMBRE, CHARINDEX(' ', NOMBRE) + 1, 20)))) 
									END),

			@VP_APELLIDO		=	(CASE	
										WHEN K_USUARIO_PEARL <> 86		THEN UPPER(LEFT(APELLIDO_PATERNO,1)) + LOWER(SUBSTRING(APELLIDO_PATERNO,2,LEN(APELLIDO_PATERNO)))
										WHEN K_USUARIO_PEARL = 86		THEN 'Olegario'--UPPER(LEFT(SUBSTRING( NOMBRE, CHARINDEX(' ', NOMBRE) + 1, 20),1))+LOWER(SUBSTRING(SUBSTRING( NOMBRE, CHARINDEX(' ', NOMBRE) + 1, 20),2,LEN(SUBSTRING( NOMBRE, CHARINDEX(' ', NOMBRE) + 1, 20)))) 
									END)

	FROM	BD_GENERAL.DBO.[GRUPO_APROBADOR]	(NOLOCK)
	INNER	JOIN USUARIO_PEARL (NOLOCK) ON [GRUPO_APROBADOR].K_USUARIO = USUARIO_PEARL.K_USUARIO_PEARL
	WHERE	D_USUARIO_PEARL		= @PP_USER	
	AND		S_GRUPO_APROBADOR	= @PP_PASSWORD
	AND		K_ESTATUS_GRUPO_APROBADOR	= 1		--	ACTIVO
	AND		K_TIPO_GRUPO_APROBADOR		= @VP_TIPO_GRUPO_APROBADOR--		150	--  MODIFICAR INSPECCION MATERIAL QA
	AND		K_USUARIO_TIPO				IN (10,20, 30)			

	IF @VP_K_CODIGO IS NULL OR @VP_NOMBRE IS NULL OR @VP_APELLIDO IS NULL
	BEGIN
		RAISERROR ('Los datos del Usuario no son correctos o no tienes permisos para realizar la acción solicitada.', 16, 1 )
	END
	-- /////////////////////////////////////////////////////////////////////
COMMIT TRANSACTION 
END TRY

BEGIN CATCH
	/* Ocurrió un error, deshacemos los cambios*/ 
	ROLLBACK TRANSACTION
	DECLARE @VP_ERROR_TRANS NVARCHAR(4000);
	SET @VP_ERROR_TRANS = ERROR_MESSAGE() 
	SET @VP_MENSAJE = 'ERROR:// ' + @VP_ERROR_TRANS
END CATCH
	
	IF @VP_MENSAJE<>''
	BEGIN
		SET	@VP_MENSAJE = '!!!! ' + @VP_MENSAJE 
	END

	SELECT @VP_NOMBRE + ' ' +	@VP_APELLIDO	AS NOMBRE_USUARIO,
		   						@VP_MENSAJE		AS MENSAJE
	-- //////////////////////////////////////////////////////////////

GO


