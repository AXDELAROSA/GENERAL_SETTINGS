IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[PG_RN_FORMA_PERMISO_ACCION]') AND type in (N'P', N'PC'))
	DROP PROCEDURE [dbo].[PG_RN_FORMA_PERMISO_ACCION]
GO

--	EXEC [PG_RN_FORMA_PERMISO_ACCION] 0,144, 'FoliosV2', 'BT_ISSUE_OUT', 144

CREATE PROCEDURE [dbo].[PG_RN_FORMA_PERMISO_ACCION]
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO_ACCION		INT,
	-- ===========================	
	@PP_FORMA					VARCHAR(100),
	@PP_BOTON					VARCHAR(50),
	@PP_CODIGO_USUARIO			INT
	-- ===========================		
AS

	DECLARE @VP_RESULTADO		VARCHAR(300) = '' 
	
	-- /////////////////////////////////////////////////////

	IF @VP_RESULTADO=''
		IF NOT EXISTS(	SELECT	K_FORMA_PERMISO_ACCION 
					FROM	BD_GENERAL.DBO.FORMA_PERMISO_ACCION 
					WHERE	K_USUARIO = @PP_CODIGO_USUARIO	
					AND		D_FORMA_PERMISO_ACCION = @PP_FORMA
					AND		K_ESTATUS_FORMA_PERMISO_ACCION = 1 -- ACTIVO
				)
			BEGIN
				SET @VP_RESULTADO =  'Usuario  <NO AUTORIZADO>...' 
			END
	-- /////////////////////////////////////////////////////
	
	SELECT @VP_RESULTADO AS MENSAJE

	-- /////////////////////////////////////////////////////
GO




