CREATE PROCEDURE [dbo].[PG_CI_COUNTRY]
	--@PP_L_DEBUG					INT,
	@PP_K_SISTEMA_EXE			INT,
	@PP_K_USUARIO_ACCION		INT,
	-- ========================================
	@PP_K_COUNTRY				INT,			
	@PP_D_COUNTRY				VARCHAR(100),
	@PP_S_COUNTRY				VARCHAR(10),
	@PP_O_COUNTRY				INT,
	@PP_C_COUNTRY				VARCHAR(255),
	@PP_L_COUNTRY				INT,
	-- =========================================
	@PP_K_CONTINENTE			INT
AS
	
	-- ===============================

	DECLARE @VP_K_EXISTE	INT

	SELECT	@VP_K_EXISTE =	K_COUNTRY
							FROM	[COUNTRY]
							WHERE	K_COUNTRY=@PP_K_COUNTRY

	-- ===============================

	IF @VP_K_EXISTE IS NULL
		INSERT INTO [COUNTRY]	
			(	[K_COUNTRY], [D_COUNTRY],
				[S_COUNTRY], [O_COUNTRY],
				[C_COUNTRY], [L_COUNTRY],
				[K_CONTINENTE], 
			-- ============================================
				[K_USUARIO_ALTA], [F_ALTA], 
				[K_USUARIO_CAMBIO], [F_CAMBIO],
				[L_BORRADO], [K_USUARIO_BAJA], [F_BAJA]  )		
		VALUES	
			(	@PP_K_COUNTRY, @PP_D_COUNTRY,
				@PP_S_COUNTRY, @PP_O_COUNTRY, 
				@PP_C_COUNTRY, @PP_L_COUNTRY,
				@PP_K_CONTINENTE,		
			-- ============================================
				@PP_K_USUARIO_ACCION, GETDATE(), 
				@PP_K_USUARIO_ACCION, GETDATE(),
				0, NULL, NULL )							
	ELSE
		UPDATE	COUNTRY
		SET		
				[D_COUNTRY]				= @PP_D_COUNTRY,					
				[S_COUNTRY]				= @PP_S_COUNTRY,					
				[C_COUNTRY]				= @PP_C_COUNTRY,
				[K_CONTINENTE]			= @PP_K_CONTINENTE,
			-- ===========================
				[K_USUARIO_CAMBIO]			= @PP_K_USUARIO_ACCION, 
				[F_CAMBIO]					= GETDATE() 
		WHERE	K_COUNTRY=@PP_K_COUNTRY
	-- =========================================================
GO



