IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[PG_CI_COUNTRY]') AND type in (N'P', N'PC'))
	DROP PROCEDURE [dbo].[PG_CI_COUNTRY]
